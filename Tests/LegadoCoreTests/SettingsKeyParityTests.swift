    func testEveryUpstreamPreferenceIsRepresented() {
        let port = Set(SettingsKey.allCases.map(\.rawValue))
        let missing = Self.upstreamKeys.subtracting(port)
        XCTAssertTrue(
            missing.isEmpty,
            "the preferences the port cannot represent: \(missing.sorted().joined(separator: ", "))"
        )
    }

    func testThePortDoesNotInventKeys() {
        let upstream = Self.upstreamKeys
        let invented = Set(SettingsKey.allCases.map(\.rawValue)).subtracting(upstream)
        XCTAssertTrue(
            invented.isEmpty,
            "the preferences that are not upstream: \(invented.sorted().joined(separator: ", "))"
        )
    }
