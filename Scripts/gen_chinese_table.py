#!/usr/bin/env python3
"""Generates the Swift tables of the simplified/traditional converter.

The upstream uses `com.github.liuyueyi.quick-transfer.ChineseUtils`, whose
dictionaries are OpenCC derived; this script converts the OpenCC data files
into the Swift sources of the port.

Usage: python3 gen_chinese_table.py <opencc-dir> <out-dir>

The OpenCC data files (see Scripts/fetch_opencc.sh):
  * TSCharacters.txt — traditional → simplified characters
  * STCharacters.txt — simplified → traditional characters
  * TSPhrases.txt   — traditional → simplified phrases
  * STPhrases.txt   — simplified → traditional phrases
"""

import os
import sys


def read_lines(path):
    with open(path, encoding="utf-8") as handle:
        for line in handle:
            line = line.rstrip("\n")
            if not line or line.startswith("#"):
                continue
            yield line


def read_characters(path):
    """{key: first candidate} of a character dictionary."""
    pairs = {}
    for line in read_lines(path):
        parts = line.split()
        if len(parts) < 2:
            continue
        key = parts[0]
        value = parts[1]
        if len(key) != 1 or len(value) != 1 or key == value:
            continue
        pairs[key] = value
    return pairs


def read_phrases(path):
    """{key: value} of a phrase dictionary."""
    pairs = {}
    for line in read_lines(path):
        parts = line.split("\t")
        if len(parts) < 2:
            parts = line.split()
            if len(parts) < 2:
                continue
        key = parts[0]
        value = parts[1].strip()
        if not key or not value or key == value:
            continue
        pairs[key] = value
    return pairs


def swift_literal(text):
    """Escapes a string for a Swift literal."""
    return (
        text.replace("\\", "\\\\")
        .replace('"', '\\"')
        .replace("\n", "\\n")
        .replace("\r", "\\r")
        .replace("\t", "\\t")
    )


def write_characters(path, tables):
    """Writes the parallel source/target strings of the character tables."""
    with open(path, "w", encoding="utf-8") as out:
        out.write("//\n")
        out.write("//  ChineseCharacters.swift\n")
        out.write("//  LegadoCore\n")
        out.write("//\n")
        out.write("//  GENERATED by Scripts/gen_chinese_table.py from the OpenCC data\n")
        out.write("//  files — the upstream uses the quick-transfer library, whose\n")
        out.write("//  dictionaries are OpenCC derived.\n")
        out.write("//\n")
        out.write("//  Do not edit by hand.\n")
        out.write("//\n\n")
        out.write("/// The character tables of the Chinese converter.\n")
        out.write("public enum ChineseCharacters {\n")
        for name, description, pairs in tables:
            source = "".join(pairs.keys())
            target = "".join(pairs.values())
            out.write("\n")
            out.write("    /// The %s characters (%d entries).\n" % (description, len(source)))
            out.write("    public static let %sSource = \"%s\"\n" % (name, swift_literal(source)))
            out.write("    /// The matching %s characters.\n" % description)
            out.write("    public static let %sTarget = \"%s\"\n" % (name, swift_literal(target)))
        out.write("}\n")
    return sum(len(pairs) for _, _, pairs in tables)


def write_phrases(path, tables):
    """Writes the `key\\tvalue` phrase tables."""
    with open(path, "w", encoding="utf-8") as out:
        out.write("//\n")
        out.write("//  ChinesePhrases.swift\n")
        out.write("//  LegadoCore\n")
        out.write("//\n")
        out.write("//  GENERATED by Scripts/gen_chinese_table.py from the OpenCC data\n")
        out.write("//  files — the upstream uses the quick-transfer library, whose\n")
        out.write("//  dictionaries are OpenCC derived.\n")
        out.write("//\n")
        out.write("//  Do not edit by hand.\n")
        out.write("//\n\n")
        out.write("/// The phrase tables of the Chinese converter.\n")
        out.write("///\n")
        out.write("/// Every entry is a `key\\tvalue` pair; the entries are separated by\n")
        out.write("/// newlines. The tables are parsed lazily when a conversion runs.\n")
        out.write("public enum ChinesePhrases {\n")
        for name, description, pairs in tables:
            data = "\n".join("%s\t%s" % (key, value) for key, value in pairs.items())
            out.write("\n")
            out.write("    /// The %s phrases (%d entries).\n" % (description, len(pairs)))
            out.write("    public static let %s = \"%s\"\n" % (name, swift_literal(data)))
        out.write("}\n")
    return sum(len(pairs) for _, _, pairs in tables)


def main():
    opencc_dir = sys.argv[1]
    out_dir = sys.argv[2]

    count = write_characters(
        os.path.join(out_dir, "ChineseCharacters.swift"),
        [
            (
                "traditionalToSimplified",
                "traditional → simplified",
                read_characters(os.path.join(opencc_dir, "TSCharacters.txt")),
            ),
            (
                "simplifiedToTraditional",
                "simplified → traditional",
                read_characters(os.path.join(opencc_dir, "STCharacters.txt")),
            ),
        ],
    )
    print("characters: %d" % count)

    count = write_phrases(
        os.path.join(out_dir, "ChinesePhrases.swift"),
        [
            (
                "traditionalToSimplified",
                "traditional → simplified",
                read_phrases(os.path.join(opencc_dir, "TSPhrases.txt")),
            ),
            (
                "simplifiedToTraditional",
                "simplified → traditional",
                read_phrases(os.path.join(opencc_dir, "STPhrases.txt")),
            ),
        ],
    )
    print("phrases: %d" % count)


if __name__ == "__main__":
    main()
