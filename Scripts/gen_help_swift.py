#!/usr/bin/env python3
"""Generates the Swift files that embed the upstream's help documents.

* Sources/LegadoUI/SourceEditorHelp.swift — the source editor's three
  tutorials (ruleHelp.md, jsHelp.md, regexHelp.md).
* Sources/LegadoUI/AppHelpDocuments.swift — the documents the app itself
  shows (appHelp.md, dictRuleHelp.md, txtTocRuleHelp.md, httpTTSHelp.md,
  webDavBookHelp.md).

The upstream files live in app/src/main/assets/web/help/md/.
"""
import pathlib
import sys

ROOT = pathlib.Path("/mnt/d/code/vscode/legado")
UPSTREAM = ROOT / "app/src/main/assets/web/help/md"
PORT = pathlib.Path("/mnt/d/code/vscode/legado-ios/Sources/LegadoUI")


def swift_literal(text: str) -> str:
    escaped = text.replace("\\", "\\\\").replace('"""', '\\"\\"\\"')
    # A multi-line string literal must not end with a backslash before the
    # closing delimiter.
    if escaped.endswith("\\"):
        escaped = escaped[:-1] + "\\\\"
    # Every line is indented by eight spaces so that the closing delimiter can
    # keep the same indentation (Swift strips the common prefix).
    lines = escaped.split("\n")
    body = "\n".join(("        " + line) if line else "" for line in lines)
    return '        """\n' + body + '\n        """'


HEADER = '''//
//  {file}
//  LegadoUI
//
//  {comment}
//
//  GENERATED by Scripts/gen_help_swift.py — do not edit.
//
//  The upstream files live in
//  app/src/main/assets/web/help/md/.
//

#if canImport(SwiftUI)
import SwiftUI
#else
import LegadoUIShim
#endif

import LegadoCore
'''


def write_source_editor_help() -> None:
    js = (UPSTREAM / "jsHelp.md").read_text(encoding="utf-8")
    regex = (UPSTREAM / "regexHelp.md").read_text(encoding="utf-8")
    rule = (UPSTREAM / "ruleHelp.md").read_text(encoding="utf-8")
    body = HEADER.format(
        file="SourceEditorHelp.swift",
        comment=(
            "The help documents of the source editor.\n//\n"
            "//  Upstream:\n"
            "//  app/src/main/java/io/legado/app/ui/book/source/edit/BookSourceEditActivity.kt:587-624\n"
            "//  app/src/main/java/io/legado/app/ui/widget/dialog/UrlOptionDialog.kt"
        ),
    ) + f'''
/// The help documents of the source editor — upstream
/// `BookSourceEditActivity.helpActions()`.
public enum SourceEditorHelp {{

    /// The rule syntax reference — upstream `assets/web/help/md/ruleHelp.md`.
    public static let ruleHelp = {swift_literal(rule)}

    /// The JavaScript tutorial — upstream `assets/web/help/md/jsHelp.md`.
    public static let jsHelp = {swift_literal(js)}

    /// The regular expression tutorial — upstream
    /// `assets/web/help/md/regexHelp.md`.
    public static let regexHelp = {swift_literal(regex)}
}}
'''
    target = PORT / "SourceEditorHelp.swift"
    target.write_text(body, encoding="utf-8")
    print("written", target, len(body))


def write_app_help_documents() -> None:
    names = {
        "appHelp": "appHelp.md",
        "dictRuleHelp": "dictRuleHelp.md",
        "txtTocRuleHelp": "txtTocRuleHelp.md",
        "httpTTSHelp": "httpTTSHelp.md",
        "webDavBookHelp": "webDavBookHelp.md",
    }
    literals = []
    comments = []
    for name, file_name in names.items():
        text = (UPSTREAM / file_name).read_text(encoding="utf-8")
        comments.append(
            f"    /// The `{file_name}` document — upstream\n"
            f"    /// `assets/web/help/md/{file_name}`.\n"
            f"    public static let {name} = {swift_literal(text)}"
        )
    body = HEADER.format(
        file="AppHelpDocuments.swift",
        comment=(
            "The documents the app itself shows: the help of the app, the\n"
            "//  help of the dictionary rules, the help of the TXT chapter rules, the\n"
            "//  help of the HTTP TTS engines and the help of the remote books."
        ),
    ) + "\n/// The documents the app shows — upstream `ui/main/my/MyFragment.kt:70`,\n" \
        "/// `ui/dict/rule/DictRuleActivity.kt:137`, `ui/book/toc/rule/TxtTocRuleActivity.kt:137`,\n" \
        "/// `ui/book/read/config/SpeakEngineDialog.kt` and\n" \
        "/// `ui/book/import/remote/RemoteBookActivity.kt:89`.\n" \
        "public enum AppHelpDocuments {\n\n" \
        + "\n\n".join(comments) \
        + "\n}\n"
    target = PORT / "AppHelpDocuments.swift"
    target.write_text(body, encoding="utf-8")
    print("written", target, len(body))


def main() -> int:
    write_source_editor_help()
    write_app_help_documents()
    return 0


if __name__ == "__main__":
    sys.exit(main())
